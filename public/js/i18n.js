const STORAGE_KEY = 'xyzt_lang';
let currentLang = 'en';

export function initialLanguage() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && dictionary[saved]) return saved;
    return (navigator.language || 'en').toLowerCase().startsWith('it') ? 'it' : 'en';
}

export function t(key, vars = {}) {
    const text = dictionary[currentLang][key] ?? dictionary.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}

// data-i18n fills the text, data-i18n-ph the placeholder, data-i18n-aria the accessible name.
export function setLanguage(lang) {
    currentLang = dictionary[lang] ? lang : 'en';
    localStorage.setItem(STORAGE_KEY, currentLang);
    document.documentElement.lang = currentLang;
    document.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
    document.querySelectorAll('[data-i18n-ph]').forEach(node => { node.placeholder = t(node.dataset.i18nPh); });
    document.querySelectorAll('[data-i18n-aria]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nAria)); });
}
